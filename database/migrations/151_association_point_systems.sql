-- 151: the associations' own points charts, entered as GaitDesk standard systems.
--
-- Researched from each association's published rules and entered as printed.
-- Each is a **GaitDesk standard** system (company_id NULL): every show company
-- can see it and choose it for a show or a circuit, only a GaitDesk admin edits
-- it, and a company that scores differently copies it and changes the copy.
-- Every chart's `notes` names the rule and the edition it was read from.
--
--   APHA   Rule Book SC-060.A.1 (2022 text; not amended through 2026)
--   ApHC   Official Handbook 2026, rule 701.A
--   FQHR   Rule Book 2026, F.Q.H.R. Points
--   NSBA   Rulebook rule 42 (traditional, 2026 edition); year-end base points
--          from NSBA's announcement of January 2024
--   WSCA   Official Rulebook 2025-2027, rules 11 (color points) and 12
--          (Championship Show)
--
-- Not entered, on purpose:
--
--   AQHA    Its rulebook could not be read from an American source (AQHA's
--           site refuses automated reads); a chart copied from elsewhere would
--           be read at the rail as AQHA's.
--   MNSPHC  The club publishes no points chart; its show bills name its
--           circuit and year-end awards without saying how they are scored.
--
-- A row awards no more places than its class size (migration 150), so a chart
-- that pays the same whatever the class size is a row per size up to its last
-- place. Generated by a script that checks that rule, and the NSBA year-end
-- chart against NSBA's own worked example, before writing any SQL.
--
-- Idempotent: a standard system of the same name is left alone, so an admin's
-- corrections are never overwritten by re-running this.

