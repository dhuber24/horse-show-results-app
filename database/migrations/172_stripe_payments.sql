-- 172: online payments through Stripe.
--
-- Until now the app took no payment: GaitDesk invoiced show companies and
-- trainers by hand, and a show office wrote down the cash and checks it took.
-- Stripe now carries three kinds of money, and none of them through GaitDesk's
-- hands but its own:
--
--   * **Trainer Registry Pro** is a Stripe subscription billed to the
--     trainer's card; GaitDesk pays the processing fee. Each paid renewal
--     moves `trainers.pro_until` to the end of the period paid for, so Pro is
--     still a date -- a cancelled subscription simply stops moving it.
--     `stripe_customer_id` / `stripe_subscription_id` tie the trainer to it.
--
--   * **GaitDesk invoices a show company**, net 30 (`gaitdesk_invoices`,
--     `gaitdesk_invoice_lines`): the shows on its usage statement and any
--     unpaid Pro+ year, issued by a GaitDesk admin. The company pays by bank
--     (ACH) at no charge, or by credit card plus the processing fee
--     (`card_fee_cents`); a check or wire is marked paid by an admin. GaitDesk
--     never takes anything out of an exhibitor's payment.
--
--   * **A show company takes exhibitors' payments** on its own Stripe account
--     (Connect, Standard accounts): the money goes from the exhibitor to the
--     company and never through GaitDesk. `show_companies.stripe_account_id`
--     is that account, and `pass_card_fees` is the company's choice to charge
--     credit card payers the processing fee or absorb it. An online payment
--     lands in `show_payments` like any other, with the fee in its own column
--     (`card_fee_cents`) so it is never credited against the bill.
--
-- `stripe_events` records each webhook event handled, so a retried delivery
-- is applied once.
--
-- New tables and nullable or defaulted columns: backward-compatible, so this
-- goes to production before the code. The running release never names them.

BEGIN;

-- Trainer Registry Pro by subscription.
ALTER TABLE trainers ADD COLUMN IF NOT EXISTS stripe_customer_id TEXT;
ALTER TABLE trainers ADD COLUMN IF NOT EXISTS stripe_subscription_id TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS uq_trainers_stripe_customer
    ON trainers (stripe_customer_id) WHERE stripe_customer_id IS NOT NULL;

-- A show company's own Stripe account, and who pays the card fee.
ALTER TABLE show_companies ADD COLUMN IF NOT EXISTS stripe_account_id TEXT;
-- New NOT NULL columns are added with their default in one statement: every
-- existing row takes the default, and the running release, which never names
-- them, inserts without them and gets it too.
ALTER TABLE show_companies ADD COLUMN IF NOT EXISTS stripe_charges_enabled BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE show_companies ADD COLUMN IF NOT EXISTS pass_card_fees BOOLEAN NOT NULL DEFAULT false;
CREATE UNIQUE INDEX IF NOT EXISTS uq_show_companies_stripe_account
    ON show_companies (stripe_account_id) WHERE stripe_account_id IS NOT NULL;

-- An exhibitor's online payment, recorded like the desk's.
ALTER TABLE show_payments ADD COLUMN IF NOT EXISTS card_fee_cents INTEGER NOT NULL DEFAULT 0;
ALTER TABLE show_payments ADD COLUMN IF NOT EXISTS stripe_payment_intent_id TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS uq_show_payments_stripe_payment_intent
    ON show_payments (stripe_payment_intent_id) WHERE stripe_payment_intent_id IS NOT NULL;

-- What GaitDesk invoices a show company.
CREATE TABLE IF NOT EXISTS gaitdesk_invoices (
    id                       UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    number                   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    company_id               UUID REFERENCES show_companies(id) ON DELETE SET NULL,
    company_name             TEXT NOT NULL,
    issued_on                DATE NOT NULL,
    due_on                   DATE NOT NULL,
    amount_cents             INTEGER NOT NULL,
    note                     TEXT,
    issued_by_user_id        UUID REFERENCES users(id) ON DELETE SET NULL,
    created_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
    voided_at                TIMESTAMPTZ,
    paid_on                  DATE,
    payment_method           TEXT,
    payment_reference        TEXT,
    card_fee_cents           INTEGER NOT NULL DEFAULT 0,
    stripe_payment_intent_id TEXT,
    payment_pending_at       TIMESTAMPTZ,
    CONSTRAINT uq_gaitdesk_invoices_number UNIQUE (number),
    CONSTRAINT ck_gaitdesk_invoices_amount CHECK (amount_cents >= 0),
    CONSTRAINT ck_gaitdesk_invoices_due CHECK (due_on >= issued_on),
    CONSTRAINT ck_gaitdesk_invoices_card_fee CHECK (card_fee_cents >= 0),
    CONSTRAINT ck_gaitdesk_invoices_method
        CHECK (payment_method IS NULL OR payment_method IN ('card', 'ach', 'check', 'wire', 'other'))
);
ALTER TABLE gaitdesk_invoices ALTER COLUMN id SET DEFAULT gen_random_uuid();
ALTER TABLE gaitdesk_invoices ALTER COLUMN created_at SET DEFAULT now();
ALTER TABLE gaitdesk_invoices ALTER COLUMN card_fee_cents SET DEFAULT 0;
CREATE INDEX IF NOT EXISTS idx_gaitdesk_invoices_company ON gaitdesk_invoices (company_id, issued_on);
CREATE INDEX IF NOT EXISTS idx_gaitdesk_invoices_payment_intent
    ON gaitdesk_invoices (stripe_payment_intent_id) WHERE stripe_payment_intent_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS gaitdesk_invoice_lines (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    invoice_id      UUID NOT NULL REFERENCES gaitdesk_invoices(id) ON DELETE CASCADE,
    kind            TEXT NOT NULL,
    show_id         UUID REFERENCES shows(id) ON DELETE SET NULL,
    subscription_id UUID REFERENCES show_company_subscriptions(id) ON DELETE SET NULL,
    description     TEXT NOT NULL,
    billing_plan    TEXT,
    exhibitor_count INTEGER,
    rate_cents      INTEGER,
    amount_cents    INTEGER NOT NULL,
    CONSTRAINT ck_gaitdesk_invoice_lines_kind CHECK (kind IN ('show', 'pro_plus')),
    CONSTRAINT ck_gaitdesk_invoice_lines_amount CHECK (amount_cents >= 0)
);
ALTER TABLE gaitdesk_invoice_lines ALTER COLUMN id SET DEFAULT gen_random_uuid();
CREATE INDEX IF NOT EXISTS idx_gaitdesk_invoice_lines_invoice ON gaitdesk_invoice_lines (invoice_id);
CREATE INDEX IF NOT EXISTS idx_gaitdesk_invoice_lines_show
    ON gaitdesk_invoice_lines (show_id) WHERE show_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_gaitdesk_invoice_lines_subscription
    ON gaitdesk_invoice_lines (subscription_id) WHERE subscription_id IS NOT NULL;

-- Each Stripe webhook event handled, so a retried delivery is applied once.
CREATE TABLE IF NOT EXISTS stripe_events (
    id          TEXT PRIMARY KEY,
    type        TEXT NOT NULL,
    received_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE stripe_events ALTER COLUMN received_at SET DEFAULT now();

INSERT INTO _migrations (name) VALUES ('172_stripe_payments.sql')
ON CONFLICT DO NOTHING;

COMMIT;
