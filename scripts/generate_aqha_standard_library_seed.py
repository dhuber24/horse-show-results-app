"""Generate the AQHA standard library seed SQL from the 2026 AQHA Class CSV.

Reads:  database/seeds/aqha_standard_classes.csv
Writes: database/migrations/070_seed_aqha_standard_library.sql

Re-run whenever the AQHA CSV changes:
    python scripts/generate_aqha_standard_library_seed.py

The generated migration:
  1. Deletes existing AQHA-scoped rows from standard_classes, standard_division_sections,
     standard_sections, standard_divisions (clean re-seed).
  2. Inserts a curated standard_divisions row for every discipline produced by the
     classifier, with default_score_type set from the classifier's hint.
  3. Inserts standard_sections rows for every refined section the classifier emits.
  4. Inserts standard_division_sections for every (discipline, section) pair seen.
  5. Inserts one standard_classes row per CSV entry, joined to the lookup tables
     by name.

Classes whose names don't match any keyword in rules/disciplines.py are skipped
and listed at the top of the generated SQL as a sanity-check comment.
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))

from rules.disciplines import classify_class_name  # noqa: E402
from rules.sections import classify_section        # noqa: E402

CSV_PATH = ROOT / "database" / "seeds" / "aqha_standard_classes.csv"
OUT_PATH = ROOT / "database" / "migrations" / "070_seed_aqha_standard_library.sql"

# Curated section ordering — sensible defaults so the Matrix picker's column
# order reads naturally. Anything not listed gets appended at the end.
SECTION_ORDER = [
    "Open",
    "Select (50+)",
    "Novice Amateur",
    "Amateur",
    "Youth 14-18",
    "Youth 13 & Under",
    "Walk-Trot",
    "Walk-Trot 14-18",
    "Walk-Trot 13 & Under",
    "Lead Line",
    "Equestrians With Disabilities",
]


def sql_str(s: str | None) -> str:
    if s is None:
        return "NULL"
    return "'" + s.replace("'", "''") + "'"


def sql_int(n: int | None) -> str:
    return "NULL" if n is None else str(n)


def main() -> None:
    if not CSV_PATH.exists():
        sys.exit(f"AQHA CSV not found at {CSV_PATH}")

    rows: list[tuple[str, str, str, str, str, int, int | None]] = []
    skipped: list[tuple[str, str]] = []
    divisions: dict[str, str] = {}  # discipline_name -> default_score_type
    sections: set[str] = set()
    pairs: set[tuple[str, str]] = set()

    with CSV_PATH.open(encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            code = (row.get("code") or "").strip()
            name = (row.get("name") or "").strip()
            base_bracket = (row.get("division") or "").strip()
            try:
                sort_order = int(row.get("sort_order") or 0)
            except ValueError:
                sort_order = 0
            try:
                source_year_raw = (row.get("source_year") or "").strip()
                source_year = int(source_year_raw) if source_year_raw else None
            except ValueError:
                source_year = None

            classified = classify_class_name(name)
            if classified is None:
                skipped.append((code, name))
                continue
            discipline, score_type = classified
            section = classify_section(name, base_bracket)

            # First-seen score_type wins for a discipline. Classifier is consistent
            # per discipline by construction (same keyword → same score_type).
            divisions.setdefault(discipline, score_type)
            sections.add(section)
            pairs.add((discipline, section))
            rows.append((code, name, discipline, section, score_type, sort_order, source_year))

    if not rows:
        sys.exit("No classifiable rows found — refusing to write empty seed")

    # Stable, curated ordering for sections.
    section_sort: dict[str, int] = {}
    sorted_sections = [s for s in SECTION_ORDER if s in sections]
    sorted_sections += sorted(s for s in sections if s not in SECTION_ORDER)
    for i, s in enumerate(sorted_sections):
        section_sort[s] = (i + 1) * 10

    # First-encountered ordering for divisions (rough show-day order).
    division_sort: dict[str, int] = {}
    for i, d in enumerate(divisions.keys()):
        division_sort[d] = (i + 1) * 10

    out = []
    out.append("-- Migration 070: Seed AQHA standard library (Standard Library matrix picker)")
    out.append("--")
    out.append("-- GENERATED by scripts/generate_aqha_standard_library_seed.py")
    out.append("-- DO NOT edit by hand — re-run the generator after CSV changes.")
    out.append("--")
    out.append("-- Sources:")
    out.append("--   database/seeds/aqha_standard_classes.csv  (2026 AQHA Class Master Listing)")
    out.append("--   backend/rules/disciplines.py  (name → discipline classifier)")
    out.append("--   backend/rules/sections.py     (name → section classifier)")
    out.append("--")
    out.append(f"-- Classifier coverage: {len(rows)} classes mapped, {len(skipped)} unmapped.")
    if skipped:
        out.append("-- Unmapped classes (left out of standard_classes — add keywords to disciplines.py):")
        for code, name in skipped[:50]:
            out.append(f"--   {code}  {name}")
        if len(skipped) > 50:
            out.append(f"--   ... and {len(skipped) - 50} more")
    out.append("")
    out.append("BEGIN;")
    out.append("")
    out.append("-- ── 1a. Ensure server-side UUID defaults on the seed targets ─────────────")
    out.append("-- SQLAlchemy's create_all() can race ahead of migrations and create the")
    out.append("-- tables without server defaults (only Python-side default=uuid.uuid4),")
    out.append("-- which makes direct SQL INSERTs fail with NOT NULL violations on `id`.")
    out.append("-- This is idempotent: ALTER ... SET DEFAULT is a no-op when already set.")
    out.append("ALTER TABLE standard_sections ALTER COLUMN id SET DEFAULT gen_random_uuid();")
    out.append("ALTER TABLE standard_classes  ALTER COLUMN id SET DEFAULT gen_random_uuid();")
    out.append("")
    out.append("-- ── 1b. Clean slate for AQHA rows ────────────────────────────────────────")
    out.append("DELETE FROM standard_classes")
    out.append("    WHERE show_type_id = (SELECT id FROM show_types WHERE code = 'AQHA');")
    out.append("DELETE FROM standard_division_sections sds")
    out.append("    USING standard_divisions d")
    out.append("    WHERE sds.standard_division_id = d.id")
    out.append("      AND d.show_type_id = (SELECT id FROM show_types WHERE code = 'AQHA');")
    out.append("DELETE FROM standard_divisions")
    out.append("    WHERE show_type_id = (SELECT id FROM show_types WHERE code = 'AQHA');")
    out.append("DELETE FROM standard_sections")
    out.append("    WHERE show_type_id = (SELECT id FROM show_types WHERE code = 'AQHA');")
    out.append("")

    out.append("-- ── 2. AQHA standard_divisions (disciplines) ────────────────────────────")
    out.append("INSERT INTO standard_divisions (id, show_type_id, name, sort_order, default_score_type)")
    out.append("SELECT gen_random_uuid(), st.id, v.name, v.sort_order, v.score_type")
    out.append("FROM show_types st CROSS JOIN (VALUES")
    div_values = []
    for d, score_type in divisions.items():
        div_values.append(f"    ({sql_str(d)}, {division_sort[d]}, {sql_str(score_type)})")
    out.append(",\n".join(div_values))
    out.append(") AS v(name, sort_order, score_type)")
    out.append("WHERE st.code = 'AQHA';")
    out.append("")

    out.append("-- ── 3. AQHA standard_sections (brackets) ────────────────────────────────")
    out.append("INSERT INTO standard_sections (id, show_type_id, name, sort_order)")
    out.append("SELECT gen_random_uuid(), st.id, v.name, v.sort_order")
    out.append("FROM show_types st CROSS JOIN (VALUES")
    sec_values = []
    for s in sorted_sections:
        sec_values.append(f"    ({sql_str(s)}, {section_sort[s]})")
    out.append(",\n".join(sec_values))
    out.append(") AS v(name, sort_order)")
    out.append("WHERE st.code = 'AQHA';")
    out.append("")

    out.append("-- ── 4. AQHA standard_division_sections (valid pairs) ───────────────────")
    out.append("INSERT INTO standard_division_sections (standard_division_id, standard_section_id)")
    out.append("SELECT d.id, s.id")
    out.append("FROM show_types st")
    out.append("JOIN standard_divisions d ON d.show_type_id = st.id")
    out.append("JOIN standard_sections  s ON s.show_type_id = st.id")
    out.append("JOIN (VALUES")
    pair_values = []
    for d, s in sorted(pairs):
        pair_values.append(f"    ({sql_str(d)}, {sql_str(s)})")
    out.append(",\n".join(pair_values))
    out.append(") AS v(div_name, sec_name) ON v.div_name = d.name AND v.sec_name = s.name")
    out.append("WHERE st.code = 'AQHA';")
    out.append("")

    out.append("-- ── 5. AQHA standard_classes (one per CSV row that classified) ─────────")
    # Chunk inserts to keep statements readable (and within reasonable size).
    CHUNK = 200
    for chunk_start in range(0, len(rows), CHUNK):
        chunk = rows[chunk_start:chunk_start + CHUNK]
        out.append("INSERT INTO standard_classes (")
        out.append("    id, show_type_id, standard_division_id, standard_section_id,")
        out.append("    class_code, class_name, default_score_type, sort_order, source_year)")
        out.append("SELECT gen_random_uuid(), st.id, d.id, s.id, v.code, v.cname, v.score_type, v.sort_order, v.source_year")
        out.append("FROM show_types st")
        out.append("JOIN standard_divisions d ON d.show_type_id = st.id")
        out.append("JOIN standard_sections  s ON s.show_type_id = st.id")
        out.append("JOIN (VALUES")
        class_values = []
        for code, name, disc, sec, score_type, sort_order, source_year in chunk:
            class_values.append(
                f"    ({sql_str(code)}, {sql_str(name)}, {sql_str(disc)}, "
                f"{sql_str(sec)}, {sql_str(score_type)}, {sort_order}, {sql_int(source_year)})"
            )
        out.append(",\n".join(class_values))
        out.append(") AS v(code, cname, div_name, sec_name, score_type, sort_order, source_year)")
        out.append("    ON d.name = v.div_name AND s.name = v.sec_name")
        out.append("WHERE st.code = 'AQHA'")
        out.append("ON CONFLICT (show_type_id, class_code) DO NOTHING;")
        out.append("")

    out.append("INSERT INTO _migrations (name) VALUES ('070_seed_aqha_standard_library.sql') ON CONFLICT DO NOTHING;")
    out.append("")
    out.append("COMMIT;")
    out.append("")

    OUT_PATH.write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {OUT_PATH}")
    print(f"  {len(rows)} classes  |  {len(divisions)} divisions  |  {len(sorted_sections)} sections  |  {len(pairs)} pairs")
    if skipped:
        print(f"  {len(skipped)} unclassified classes — see SQL header comment for the list")


if __name__ == "__main__":
    main()
